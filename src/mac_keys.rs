pub fn code_from_key(key: Key) -> Option<CGKeyCode> {
    if let Key::Unknown(c) = key {
        return CGKeyCode::try_from(c).ok();
    }
    TABLE.iter().find(|(k, _)| *k == key).map(|(_, c)| *c)
}

pub fn key_from_code(code: CGKeyCode) -> Key {
    TABLE
        .iter()
        .find(|(_, c)| *c == code)
        .map(|(k, _)| *k)
        .unwrap_or(Key::Unknown(code as u32))
}
